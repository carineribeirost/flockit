"""Monomers (YAML templates) and building of vinyl chains H-[CH2-CH(R)]n-H.

The initial conformation is a random coil generated by growth: at each step a
backbone carbon is added (trans or gauche+/- dihedral) and the previous carbon
receives its substituents (H and side group). Steps that create overlaps are
re-drawn and, if needed, the chain backtracks one step.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from importlib import resources
from pathlib import Path

import numpy as np
import yaml

from flockit.forcefield import opls_name
from flockit.geometry import place, three_tetrahedral, two_tetrahedral

CC_BOND, CH_BOND = 1.529, 1.090
BACKBONE_ANGLE = 112.7           # OPLS-AA CT-CT-CT
CLASH_HEAVY, CLASH_H = 2.7, 1.8  # A, minimum distance between atoms 4+ bonds apart


@dataclass
class SideAtom:
    name: str
    type: str
    bond: str
    r: float
    angle_ref: str | None = None
    angle: float | None = None
    dihedral_ref: str | None = None
    dihedral: float | str | None = None


@dataclass
class Monomer:
    name: str
    description: str
    charge: int
    types: dict[str, str]
    head_types: dict[str, str]
    tail_types: dict[str, str]
    side: list[SideAtom]
    counterion: str | None = None
    charged_group: list[str] = field(default_factory=list)

    @classmethod
    def load(cls, name_or_path: str) -> "Monomer":
        path = Path(name_or_path)
        if path.suffix not in (".yaml", ".yml"):
            path = resources.files("flockit") / "data" / "monomers" / f"{name_or_path}.yaml"
        raw = yaml.safe_load(path.read_text(encoding="utf-8"))
        side = []
        for s in raw["side"]:
            ang = s.get("angle") or [None, None]
            dih = s.get("dihedral") or [None, None]
            side.append(SideAtom(s["name"], opls_name(s["type"]), s["bond"], float(s["r"]),
                                 ang[0], ang[1], dih[0], dih[1]))
        conv = lambda d: {k: opls_name(v) for k, v in (d or {}).items()}  # noqa: E731
        return cls(raw["name"], raw.get("description", ""), int(raw.get("charge", 0)),
                   conv(raw["types"]), conv(raw.get("head_types")), conv(raw.get("tail_types")),
                   side, raw.get("counterion"), list(raw.get("charged_group", [])))

    def type_for(self, role: str, head: bool, tail: bool) -> str:
        if head and role in self.head_types:
            return self.head_types[role]
        if tail and role in self.tail_types:
            return self.tail_types[role]
        return self.types[role]


@dataclass
class Chain:
    sequence: list[str]
    names: list[str]
    types: list[str]
    positions: np.ndarray
    monomer: np.ndarray            # monomer index of each atom
    bonds: list[tuple[int, int]]
    backbone: list[int]            # indices of the backbone carbons, in order
    charged_groups: list[list[int]]
    counterions: list[str]         # one counterion per elementary charge of the units


class _Clash(Exception):
    pass


def make_sequence(cfg_polymer: dict, rng: np.random.Generator) -> list[str]:
    if cfg_polymer.get("sequence"):
        return [str(s) for s in cfg_polymer["sequence"]]
    dp = int(cfg_polymer["dp"])
    comp = cfg_polymer["composition"]
    names = list(comp)
    fracs = np.array([float(comp[n]) for n in names])
    fracs = fracs / fracs.sum()
    counts = np.floor(fracs * dp).astype(int)
    for i in np.argsort(-(fracs * dp - counts))[: dp - counts.sum()]:
        counts[i] += 1                       # hand out the remainder by largest remainders
    seq = [n for n, c in zip(names, counts) for _ in range(c)]
    rng.shuffle(seq)
    return seq


def _torsion(rng: np.random.Generator, trans_fraction: float) -> float:
    r = rng.random()
    if r < trans_fraction:
        base = 180.0
    else:
        base = 60.0 if r < trans_fraction + (1 - trans_fraction) / 2 else -60.0
    return base + rng.normal(0.0, 8.0)


class _Grower:
    def __init__(self, seq: list[Monomer], rng: np.random.Generator, tacticity: str,
                 trans_fraction: float) -> None:
        if tacticity not in ("atactic", "isotactic", "syndiotactic"):
            raise ValueError(f"unknown tacticity: {tacticity}")
        self.seq, self.rng = seq, rng
        self.tacticity, self.trans_fraction = tacticity, trans_fraction
        self.n_bb = 2 * len(seq)
        self.names: list[str] = []
        self.types: list[str] = []
        self.pos: list[np.ndarray] = []
        self.mon: list[int] = []
        self.adj: list[list[int]] = []
        self.bonds: list[tuple[int, int]] = []
        self.bb_atom: list[int] = []
        self.bb_pos: list[np.ndarray] = []

    def _add(self, name: str, typ: str, xyz, unit: int, bonded_to: int | None) -> int:
        i = len(self.names)
        self.names.append(name)
        self.types.append(typ)
        self.pos.append(np.asarray(xyz, float))
        self.mon.append(unit)
        self.adj.append([])
        if bonded_to is not None:
            self.bonds.append((bonded_to, i))
            self.adj[bonded_to].append(i)
            self.adj[i].append(bonded_to)
        return i

    def _mark(self) -> tuple[int, int, int]:
        return len(self.names), len(self.bonds), len(self.bb_atom)

    def _rollback(self, mark: tuple[int, int, int]) -> None:
        n_atoms, n_bonds, n_bb = mark
        for a, b in self.bonds[n_bonds:]:
            self.adj[a].remove(b)
            self.adj[b].remove(a)
        del self.bonds[n_bonds:]
        for lst in (self.names, self.types, self.pos, self.mon, self.adj):
            del lst[n_atoms:]
        del self.bb_atom[n_bb:], self.bb_pos[n_bb:]

    def _ok(self, start: int) -> bool:
        """New atoms (index >= start) do not overlap the others (except up to 1-4 pairs)."""
        P = np.array(self.pos)
        is_h = np.array([n.startswith("H") for n in self.names])  # template naming convention
        for a in range(start, len(P)):
            excl, frontier = {a}, {a}
            for _ in range(3):
                frontier = {nb for f in frontier for nb in self.adj[f]}
                excl |= frontier
            close = np.linalg.norm(P - P[a], axis=1) < np.where(is_h | is_h[a], CLASH_H, CLASH_HEAVY)
            close[list(excl)] = False
            if close.any():
                return False
        return True

    def _backbone_position(self, k: int) -> np.ndarray:
        if k == 0:
            return np.zeros(3)
        if k == 1:
            return np.array([CC_BOND, 0.0, 0.0])
        if k == 2:
            th = np.radians(180.0 - BACKBONE_ANGLE)
            return self.bb_pos[1] + CC_BOND * np.array([np.cos(th), np.sin(th), 0.0])
        return place(self.bb_pos[k - 3], self.bb_pos[k - 2], self.bb_pos[k - 1],
                     CC_BOND, BACKBONE_ANGLE, _torsion(self.rng, self.trans_fraction))

    def _chirality(self, unit: int) -> int:
        if self.tacticity == "isotactic":
            return 0
        if self.tacticity == "syndiotactic":
            return unit % 2
        return int(self.rng.integers(0, 2))

    def _substituents(self, k: int) -> None:
        """Add the H atoms and side group of carbon k (its backbone neighbors are already placed)."""
        unit, role = k // 2, ("CB" if k % 2 else "CA")
        mono, c, center = self.seq[unit], self.bb_atom[k], self.bb_pos[k]
        nbrs = [j for j in (k - 1, k + 1) if 0 <= j < len(self.bb_pos)]
        if len(nbrs) == 2:
            dirs = list(two_tetrahedral(center, self.bb_pos[nbrs[0]], self.bb_pos[nbrs[1]]))
            if role == "CB" and self._chirality(unit):
                dirs.reverse()
        else:  # chain end: a single backbone neighbor
            nb = nbrs[0]
            ref_k = nb + 1 if nb > k else nb - 1
            ref = self.bb_pos[ref_k] if 0 <= ref_k < len(self.bb_pos) else self.bb_pos[nb] + [0.0, 0.0, 1.0]
            dirs = three_tetrahedral(center, self.bb_pos[nb], ref)
        side_dir, h_dirs = (dirs[0], dirs[1:]) if role == "CB" else (None, dirs)
        for j, d in enumerate(h_dirs, start=1):
            self._add(f"H{role[1]}{j}", mono.types["HC"], center + CH_BOND * d, unit, c)
        if side_dir is None:
            return
        local, idx = {"CA": self.bb_pos[k - 1], "CB": center}, {"CB": c}
        phi_random = self.rng.uniform(0.0, 360.0)
        first = mono.side[0]
        s = self._add(first.name, first.type, center + first.r * side_dir, unit, c)
        local[first.name], idx[first.name] = self.pos[s], s
        for at in mono.side[1:]:
            phi = phi_random if at.dihedral == "random" else float(at.dihedral)
            xyz = place(local[at.dihedral_ref], local[at.angle_ref], local[at.bond], at.r, at.angle, phi)
            idx[at.name] = self._add(at.name, at.type, xyz, unit, idx[at.bond])
            local[at.name] = xyz

    def _step(self, k: int) -> None:
        """Place backbone carbon k (if any) and complete carbon k-1."""
        if k < self.n_bb:
            unit, role = k // 2, ("CB" if k % 2 else "CA")
            typ = self.seq[unit].type_for(role, unit == 0, unit == len(self.seq) - 1)
            xyz = self._backbone_position(k)
            a = self._add(role, typ, xyz, unit, self.bb_atom[-1] if k > 0 else None)
            self.bb_atom.append(a)
            self.bb_pos.append(np.asarray(xyz, float))
        if k >= 1:
            self._substituents(k - 1)

    def grow(self, tries: int = 30, max_backtracks: int | None = None) -> Chain:
        max_backtracks = max_backtracks or 25 * self.n_bb
        marks: list[tuple[int, int, int]] = []
        k = backtracks = 0
        while k <= self.n_bb:
            mark = self._mark()
            for _ in range(tries):
                self._step(k)
                if self._ok(mark[0]):
                    break
                self._rollback(mark)
            else:
                if not marks or backtracks >= max_backtracks:
                    raise _Clash
                backtracks += 1
                k -= 1
                self._rollback(marks.pop())
                continue
            marks.append(mark)
            k += 1
        return self._finish()

    def _finish(self) -> Chain:
        order = sorted(range(len(self.names)), key=lambda i: self.mon[i])  # stable: groups by monomer
        new = {old: i for i, old in enumerate(order)}
        names = [self.names[i] for i in order]
        mon = np.array([self.mon[i] for i in order])
        positions = np.array(self.pos)[order]
        positions -= positions.mean(axis=0)
        groups, counterions = [], []
        for u, mono in enumerate(self.seq):
            if mono.charge:
                groups.append([i for i in range(len(names)) if mon[i] == u and names[i] in mono.charged_group])
                counterions.extend([mono.counterion] * abs(mono.charge))
        return Chain([m.name for m in self.seq], names, [self.types[i] for i in order], positions, mon,
                     sorted(tuple(sorted((new[a], new[b]))) for a, b in self.bonds),
                     [new[a] for a in self.bb_atom], groups, counterions)


def build_chain(sequence: list[str], rng: np.random.Generator, tacticity: str = "atactic",
                trans_fraction: float = 0.6, restarts: int = 20) -> Chain:
    if len(sequence) < 2:
        raise ValueError("the degree of polymerization must be >= 2")
    seq = [Monomer.load(s) for s in sequence]
    for _ in range(restarts):
        try:
            return _Grower(seq, rng, tacticity, trans_fraction).grow()
        except _Clash:
            continue
    raise RuntimeError("could not generate an overlap-free conformation; "
                       "change the seed or increase trans_fraction")


def find_clashes(chain: Chain) -> list[tuple[int, int, float]]:
    """Pairs 4+ bonds apart that are closer than the limits (for validation)."""
    n = len(chain.names)
    adj = [[] for _ in range(n)]
    for a, b in chain.bonds:
        adj[a].append(b)
        adj[b].append(a)
    excl = np.eye(n, dtype=bool)
    for s in range(n):
        frontier = {s}
        for _ in range(3):
            frontier = {nb for f in frontier for nb in adj[f]}
            excl[s, list(frontier)] = True
    is_h = np.array([nm.startswith("H") for nm in chain.names])
    d = np.linalg.norm(chain.positions[:, None] - chain.positions[None], axis=-1)
    bad = (d < np.where(is_h[:, None] | is_h[None], CLASH_H, CLASH_HEAVY)) & ~excl
    return [(int(i), int(j), float(d[i, j])) for i, j in zip(*np.nonzero(np.triu(bad, 1)))]
