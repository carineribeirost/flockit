"""Extract the OPLS-AA tables from moltemplate's `oplsaa2024.lt` into JSON.

The source file was generated by moltemplate from the supporting information
of Jorgensen et al., J. Phys. Chem. B (2024), DOI 10.1021/acs.jpcb.3c06602,
and uses the BOSS numbering (same as `opls_XXX`).

Usage:
    python tools/extract_oplsaa.py [path/oplsaa2024.lt] [-o flockit/data/oplsaa2024.json]

Without a path, the script looks for the file in the installed `moltemplate`
package. Variants of the same class pattern (suffix "__n" in moltemplate) are
kept as lists; the choice among them is made in
`flockit/data/oplsaa_selections.yaml`.
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

RE_CHARGE = re.compile(
    r"set type @atom:(\d+)\s+charge\s+(\S+)\s*#\s*(\S+)\s*-\s*(\S+)\s*\|\s*(.*)$")
RE_REPLACE = re.compile(r"replace\{\s*@atom:(\d+)\s+@atom:\1_b(.*?)_a(.*?)_d(.*?)_i(.*?)\s*\}")
RE_MASS = re.compile(r"^\s*@atom:(\d+)\s+([\d.]+)\s*$")
RE_PAIR = re.compile(r"pair_coeff @atom:(\d+)_\S+ @atom:\S+\s+(\S+)\s+(\S+)")
RE_COEFF = re.compile(r"(bond|angle|dihedral|improper)_coeff @\1:(\S+)\s+([^#]+?)\s*(?:#\s*(.*))?$")


def find_default_source() -> Path:
    import moltemplate  # noqa: PLC0415 (only this tool depends on it)
    return Path(moltemplate.__file__).parent / "force_fields" / "oplsaa2024.lt"


def parse(path: Path) -> dict:
    atoms: dict[str, dict] = {}
    bonded: dict[str, dict[str, list]] = {"bond": {}, "angle": {}, "dihedral": {}, "improper": {}}
    section = None
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if line.startswith("write_once("):
            section = line
        if not line or line.startswith("#"):
            continue  # includes the "# UNTRUSTED" lines
        if m := RE_CHARGE.search(line):
            tid, q, elem, cls, desc = m.groups()
            atoms.setdefault(tid, {}).update(
                charge=float(q), element=elem, class_label=cls, description=desc.strip())
        elif m := RE_REPLACE.search(line):
            tid, b, a, d, i = m.groups()
            atoms.setdefault(tid, {})["classes"] = {"bond": b, "angle": a, "dihedral": d, "improper": i}
        elif section and "Data Masses" in section and (m := RE_MASS.match(line)):
            atoms.setdefault(m.group(1), {})["mass"] = float(m.group(2))
        elif m := RE_PAIR.search(line):
            tid, eps, sig = m.groups()
            atoms.setdefault(tid, {}).update(epsilon=float(eps), sigma=float(sig))
        elif m := RE_COEFF.search(line):
            kind, name, values, comment = m.groups()
            key, _, variant = name.partition("__")
            classes = key.split("_")
            expected = {"bond": 2, "angle": 3, "dihedral": 4, "improper": 4}[kind]
            if len(classes) != expected:
                raise ValueError(f"unexpected name for {kind}: {name}")
            bonded[kind].setdefault(key, []).append({
                "variant": int(variant) if variant else 0,
                "coeffs": [float(v) for v in values.split()],
                "comment": (comment or "").strip(),
            })
    complete = {k: v for k, v in atoms.items()
                if {"charge", "classes", "mass", "epsilon", "sigma"} <= v.keys()}
    return {
        "source": "moltemplate force_fields/oplsaa2024.lt "
                  "(Jorgensen et al., J. Phys. Chem. B 2024, DOI 10.1021/acs.jpcb.3c06602)",
        "units": "real (kcal/mol, Angstrom, degrees)",
        "styles": {"bond": "harmonic", "angle": "harmonic", "dihedral": "opls", "improper": "cvff"},
        "wildcard_char": chr(0x20AC),  # moltemplate's single-character wildcard
        "atom_types": dict(sorted(complete.items(), key=lambda kv: int(kv[0]))),
        **{f"{k}s": v for k, v in bonded.items()},
    }


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("source", nargs="?", type=Path)
    ap.add_argument("-o", "--output", type=Path,
                    default=Path(__file__).resolve().parents[1] / "flockit" / "data" / "oplsaa2024.json")
    args = ap.parse_args()
    data = parse(args.source or find_default_source())
    args.output.write_text(json.dumps(data, separators=(",", ":")), encoding="ascii")  # \u escapes keep it ASCII
    counts = {k: len(data[k]) for k in ("atom_types", "bonds", "angles", "dihedrals", "impropers")}
    print(f"{args.output}: {counts}")


if __name__ == "__main__":
    main()
